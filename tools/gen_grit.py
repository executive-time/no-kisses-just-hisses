"""NKJH: the GRIT macro's tables (docs/NKJH-SPEC.md 4) -> firmware/src/nkjh_grit.h

GRIT g (0..127) drives the whole mix into the firmware's tanh (dsp.c softclip, flat past tanh(2): the hard
clip at the top). DRIVE (Q12) = 1 + 7 g^2 / 4096: x1 .. x28.6 (+29 dB), on the mix / 4. COMP (Q12) brings a sine at -12 dBFS
back to the level it had (RMS) up to g = 64, then lets it grow by up to +2.5 dB at 127 (the limiter after it
keeps the peaks). TONE (Q15, a one-pole low-pass) darkens with g.
A sine is not a mix: a beat's peaks are squashed first, so it gets louder. tools/grit_cal.txt holds the level
(dB from GRIT 0) of the NKJH default mix at every 8th GRIT, measured by tests/nkjh_grit_test.c through the
master; COMP is moved so that mix lands on the target: 0 dB up to 64, then up to +2.5 dB at 127. Calibrate:

  GRIT_CAL=build/host/grit.txt build/host/nkjh_grit_test && tools/gen_grit.py firmware/src/nkjh_grit.h build/host/grit.txt
  (it adds the new measurement to tools/grit_cal.txt; two or three rounds until it stays within 0.5 dB)
FOLD the same way: FOLD_CAL=build/host/fold.txt build/host/nkjh_destroy_test, then
  tools/gen_grit.py firmware/src/nkjh_grit.h --fold build/host/fold.txt   (tools/fold_cal.txt)
"""
import math
import sys
from pathlib import Path

CAL = Path(__file__).with_name("grit_cal.txt")


def target(g):
    return 0.0 if g <= 64 else (g - 64) / 63 * 2.5


def load(path):
    pts = [tuple(map(float, l.split())) for l in Path(path).read_text().split("\n") if l.strip()]
    return sorted(pts)


def interp(pts, g):
    for (g0, v0), (g1, v1) in zip(pts, pts[1:]):
        if g0 <= g <= g1:
            return v0 + (v1 - v0) * (g - g0) / (g1 - g0)
    return pts[-1][1] if g > pts[-1][0] else pts[0][1]

A, N = 8000.0, 2048


def comp(d, g):
    s_in = s_out = 0.0
    for k in range(N):
        x = A * math.sin(2 * math.pi * k / N)
        u = x * d / 4096 / 4                        # (fx.c: the mix / 4 into the curve, x 4 out)
        y = 4 * math.copysign(32767 * math.tanh(min(abs(u) / 32768, 2.0)), u)
        s_in += x * x
        s_out += y * y
    c = math.sqrt(s_in / s_out)
    return 4096 * c


FOLD_CAL = Path(__file__).with_name("fold_cal.txt")


def fold_comp(measured):
    """FOLD (fx.c fold_process): its level back, from tools/fold_cal.txt; a measurement (FOLD_CAL=... from
    tests/nkjh_destroy_test.c) moves it toward the target, as GRIT's"""
    corr = load(FOLD_CAL) if FOLD_CAL.exists() else [(0.0, 0.0), (127.0, 0.0)]
    if measured:
        m = load(measured)
        corr = [(g, interp(corr, g) - (v - target(g))) for g, v in m]
        FOLD_CAL.write_text("".join(f"{int(g)} {v:.3f}\n" for g, v in corr))
    return [4096 if g == 0 else int(round(min(4096 * 10 ** (interp(corr, g) / 20), 32767))) for g in range(128)]


def main(path, measured=None, fold_measured=None):
    drive = [4096 + 7 * g * g for g in range(128)]
    corr = load(CAL) if CAL.exists() else [(0.0, 0.0), (127.0, 0.0)]       # dB added to COMP so far
    if measured:                                    # this round: what is still off from the target
        m = load(measured)
        corr = [(g, interp(corr, g) - (v - target(g))) for g, v in m]
        CAL.write_text("".join(f"{int(g)} {v:.3f}\n" for g, v in corr))
    cmp_ = [0] * 128
    for g in range(128):
        c = comp(drive[g], g) * 10 ** (interp(corr, g) / 20) if g else 4096
        cmp_[g] = int(round(min(c, 32767)))
    tone = [32767 - g * 120 for g in range(128)]
    def arr(name, typ, v):
        return f"static const {typ} {name}[128] = {{\n" + ",\n".join(
            "    " + ", ".join(str(x) for x in v[i:i + 12]) for i in range(0, 128, 12)) + "};\n"
    # RING (fx.c ring_process): the sine's phase step at 44.1 kHz, 20 .. 110 Hz up to 64, then up to 1.5 kHz
    hz = [20 * (110 / 20) ** (g / 64) if g < 64 else 110 * (1500 / 110) ** ((g - 64) / 63) for g in range(128)]
    ring = [int(round(f * 2 ** 32 / 44100)) for f in hz]
    out = ["/* generated by tools/gen_grit.py: the NKJH GRIT macro (fx.c grit_process), RING's tone (ring_process) */",
           "#pragma once",
           arr("GRIT_DRIVE", "int32_t", drive), arr("GRIT_COMP", "int16_t", cmp_), arr("GRIT_TONE", "int16_t", tone),
           arr("RING_INC", "uint32_t", ring), arr("FOLD_COMP", "int16_t", fold_comp(fold_measured))]
    open(path, "w").write("\n".join(out))
    print(f"grit: 3 x 128 -> {path}")


if __name__ == "__main__":
    a = sys.argv[1:]
    fm = a[a.index("--fold") + 1] if "--fold" in a else None
    a = [x for x in a if x != "--fold" and x != fm]
    main(a[0], a[1] if len(a) > 1 else None, fm)
